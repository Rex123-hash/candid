/**
 * PayPal integration. Orders go through the official PayPal Server SDK
 * (generated by APIMatic). Catalog Products, Payouts and webhook verification
 * aren't in that SDK yet, so they use the REST API with the same sandbox app.
 */

let sdkClient: Client | null = null;

function orders(): OrdersController {
  if (!sdkClient) {
    const { clientId, clientSecret } = paypalCredentials();
    sdkClient = new Client({
      clientCredentialsAuthCredentials: { oAuthClientId: clientId, oAuthClientSecret: clientSecret },
      environment: Environment.Sandbox,
      timeout: 20_000,
    });
  }
  return new OrdersController(sdkClient);
}

export class PayPalError extends Error {
  constructor(message: string, readonly status?: number, readonly debugId?: string) {
    super(message);
  }
}

function toPayPalError(error: unknown, action: string): PayPalError {
  if (error instanceof ApiError) {
    const body = (typeof error.result === "object" && error.result) || {};
    const issue = (body as { details?: { issue?: string }[] }).details?.[0]?.issue;
    const debugId = (body as { debug_id?: string }).debug_id;
    return new PayPalError(`PayPal couldn't ${action}${issue ? ` (${issue})` : ""}.`, error.statusCode, debugId);
  }
  return new PayPalError(`PayPal couldn't ${action}.`);
}

/**
 * Opens an order for the priced basket. "Pay now" with no shipping: a stand sale
 * is complete the moment the buyer approves, and nothing is delivered. The return
 * and cancel URLs bring a redirected buyer back to the stand page.
 */
export async function createPayPalOrder(
  stand: Stand,
  sale: Pick<Sale, "id" | "lines" | "totalCents" | "method">,
  urls: { returnUrl: string; cancelUrl: string },
): Promise<string> {
  const currencyCode = stand.currency;
  const brandName = stand.name.slice(0, 127);
  const paymentSource =
    sale.method === "venmo"
      ? {
          venmo: {
            experienceContext: {
              brandName,
              shippingPreference: VenmoWalletExperienceContextShippingPreference.NoShipping,
              userAction: VenmoWalletExperienceContextUserAction.PayNow,
            },
          },
        }
      : {
          paypal: {
            experienceContext: {
              brandName,
              shippingPreference: PaypalWalletContextShippingPreference.NoShipping,
              userAction: PaypalExperienceUserAction.PayNow,
              returnUrl: urls.returnUrl,
              cancelUrl: urls.cancelUrl,
            },
          },
        };
  try {
    const { result } = await orders().createOrder({
      paypalRequestId: `create-${sale.id}`,
      prefer: "return=minimal",
      body: {
        intent: CheckoutPaymentIntent.Capture,
        paymentSource,
        purchaseUnits: [
          {
            referenceId: stand.id,
            customId: sale.id,
            description: `${stand.name} — Candid honesty checkout`.slice(0, 127),
            amount: {
              currencyCode,
              value: centsToValue(sale.totalCents),
              breakdown: { itemTotal: { currencyCode, value: centsToValue(sale.totalCents) } },
            },
            items: sale.lines.map((line) => ({
              name: line.name.slice(0, 127),
              sku: line.itemId,
              quantity: String(line.qty),
              unitAmount: { currencyCode, value: centsToValue(line.unitCents) },
            })),
          },
        ],
      },
    });
    if (!result.id) throw new PayPalError("PayPal didn't return an order id.");
    return result.id;
  } catch (error) {
    throw error instanceof PayPalError ? error : toPayPalError(error, "create the order");
  }
}

/** The order's current status at PayPal, e.g. CREATED, APPROVED, COMPLETED. */
export async function getPayPalOrderStatus(orderId: string): Promise<string> {
  try {
    const { result } = await orders().getOrder({ id: orderId });
    return result.status ?? "UNKNOWN";
  } catch (error) {
    throw toPayPalError(error, "look up the order");
  }
}

export type CaptureOutcome =
  | { ok: true; captureId: string }
  | { ok: false; reason: string; retryable: boolean };

/**
 * Captures an approved order. The request id is stable per sale, so a retry after
 * a timeout can't charge twice. The sale only counts as paid when PayPal says the
 * capture is COMPLETED for exactly the amount we priced.
 */
export async function capturePayPalOrder(sale: Sale, currency: string): Promise<CaptureOutcome> {
  try {
    const { result } = await orders().captureOrder({
      id: sale.paypalOrderId,
      paypalRequestId: sale.captureRequestId,
      prefer: "return=representation",
    });
    const capture = result.purchaseUnits?.[0]?.payments?.captures?.[0];
    if (!capture?.id || capture.status !== "COMPLETED") {
      return { ok: false, reason: `Capture status is ${capture?.status ?? "unknown"}.`, retryable: false };
    }
    const amount = capture.amount;
    if (!amount || amount.currencyCode !== currency || valueToCents(amount.value) !== sale.totalCents) {
      return { ok: false, reason: "Captured amount doesn't match the basket total.", retryable: false };
    }
    return { ok: true, captureId: capture.id };
  } catch (error) {
    const err = toPayPalError(error, "capture the payment");
    const declined = err.message.includes("INSTRUMENT_DECLINED");
    return { ok: false, reason: declined ? "The payment method was declined. Try another one." : err.message, retryable: declined };
  }
}

// ---------- REST helpers for APIs outside the server SDK ----------

let cachedToken: { value: string; expiresAt: number } | null = null;

async function accessToken(): Promise<string> {
  if (cachedToken && cachedToken.expiresAt > Date.now() + 60_000) return cachedToken.value;
  const { clientId, clientSecret } = paypalCredentials();
  const response = await fetch(`${PAYPAL_API_BASE}/v1/oauth2/token`, {
    method: "POST",
    headers: {
      Authorization: `Basic ${Buffer.from(`${clientId}:${clientSecret}`).toString("base64")}`,
      "Content-Type": "application/x-www-form-urlencoded",
    },
    body: "grant_type=client_credentials",
    cache: "no-store",
  });
  if (!response.ok) throw new PayPalError("PayPal rejected the sandbox credentials.", response.status);
  const json = (await response.json()) as { access_token: string; expires_in: number };
  cachedToken = { value: json.access_token, expiresAt: Date.now() + json.expires_in * 1000 };
  return json.access_token;
}

async function paypalRest<T>(pathname: string, init: { method: string; body?: unknown; requestId?: string }): Promise<T> {
  const response = await fetch(`${PAYPAL_API_BASE}${pathname}`, {
    method: init.method,
    headers: {
      Authorization: `Bearer ${await accessToken()}`,
      "Content-Type": "application/json",
      ...(init.requestId ? { "PayPal-Request-Id": init.requestId } : {}),
    },
    body: init.body === undefined ? undefined : JSON.stringify(init.body),
    cache: "no-store",
  });
  const text = await response.text();
  const json = text ? JSON.parse(text) : {};
  if (!response.ok) {
    const issue = json?.details?.[0]?.issue ?? json?.name ?? response.statusText;
    throw new PayPalError(`PayPal request failed (${issue}).`, response.status, json?.debug_id);
  }
  return json as T;
}

/** Creates one PayPal catalog product per stand item. Idempotent per item. */
export async function createCatalogProduct(stand: Stand, item: Item): Promise<string> {
  const product = await paypalRest<{ id: string }>("/v1/catalogs/products", {
    method: "POST",
    requestId: `product-${stand.id}-${item.id}`,
    body: {
      name: item.name.slice(0, 127),
      description: `${item.name} (${item.unit}) at ${stand.name}`.slice(0, 256),
      type: "PHYSICAL",
      category: "FOOD_PRODUCTS",
    },
  });
  return product.id;
}

/** Sends each grower their share in one Payouts batch. */
export async function sendGrowerPayouts(
  batchKey: string,
  shares: { growerId: string; email: string; cents: number }[],
  standName: string,
): Promise<{ batchId: string; status: string }> {
  const result = await paypalRest<{ batch_header: { payout_batch_id: string; batch_status: string } }>("/v1/payments/payouts", {
    method: "POST",
    requestId: batchKey,
    body: {
      sender_batch_header: {
        sender_batch_id: batchKey,
        email_subject: `Your share from ${standName}`,
        email_message: "Here's your share of today's honesty-stand sales, sent by Candid.",
      },
      items: shares.map((share) => ({
        recipient_type: "EMAIL",
        receiver: share.email,
        sender_item_id: senderItemId(batchKey, share.growerId),
        amount: { value: centsToValue(share.cents), currency: "USD" },
        note: `Honesty-stand sales from ${standName}`,
      })),
    },
  });
  return { batchId: result.batch_header.payout_batch_id, status: result.batch_header.batch_status };
}

/** Reads a payout batch with each recipient's own status (pending, success, unclaimed, failed...). */
export async function getPayoutBatch(batchId: string): Promise<PayPalBatchView> {
  return paypalRest<PayPalBatchView>(`/v1/payments/payouts/${encodeURIComponent(batchId)}?page_size=100`, { method: "GET" });
}

/** Verifies a webhook with PayPal before we trust anything in its body. */
export async function verifyWebhook(headers: Headers, rawBody: string): Promise<boolean> {
  const webhookId = process.env.PAYPAL_WEBHOOK_ID;
  if (!webhookId) return false;
  const get = (name: string) => headers.get(name) ?? "";
  const certUrl = get("paypal-cert-url");
  // Only accept PayPal-hosted certificates; never fetch arbitrary URLs.
  if (certUrl && !/^https:\/\/api(-m)?\.(sandbox\.)?paypal\.com\//.test(certUrl)) return false;
  const result = await paypalRest<{ verification_status: string }>("/v1/notifications/verify-webhook-signature", {
    method: "POST",
    body: {
      auth_algo: get("paypal-auth-algo"),
      cert_url: certUrl,
      transmission_id: get("paypal-transmission-id"),
      transmission_sig: get("paypal-transmission-sig"),
      transmission_time: get("paypal-transmission-time"),
      webhook_id: webhookId,
      webhook_event: JSON.parse(rawBody),
    },
  });
  return result.verification_status === "SUCCESS";
}
